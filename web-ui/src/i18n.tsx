export const dictionaries: Record<Locale, Dict> = { fr, en, ru, it, de, es };

const I18nContext = createContext<{
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string, vars?: Record<string, string>) => string;
}>({
  locale: 'fr',
  setLocale: () => {},
  t: (key) => key,
});

function detectLocale(): Locale {
  const saved = localStorage.getItem('locale') as Locale | null;
  if (saved && dictionaries[saved]) return saved;
  const browser = (navigator.language || 'en').slice(0, 2).toLowerCase() as Locale;
  return dictionaries[browser] ? browser : 'en';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => detectLocale());

  useEffect(() => {
    localStorage.setItem('locale', locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const t = (key: string, vars?: Record<string, string>) => {
    let str = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      }
    }
    return str;
  };

  return (
    <I18nContext.Provider value={{ locale, setLocale: setLocaleState, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export const useT = () => useContext(I18nContext);
